# include<iostream>

using namespace std;

/*
 * lowbit(x) 表示 x 的二进制中最低位的 1 所代表的数值。
 *
 * 如果 x = 2^k * m，其中 m 是奇数，
 * 那么 x 的二进制末尾恰好有 k 个 0，因此 lowbit(x) = 2^k。
 */
long long lowbit(long long x)
{
    return x & -x;
}

/*
 * 除掉 x 中的所有因子 2，得到它的奇数部分。
 *
 * 例如：
 * 40 = 2^3 * 5，所以 get(40) = 5。
 *
 * 这道题中，若 x = 2^k * m（m 为奇数），则：
 *
 * x +/- lowbit(x)
 * = 2^k * (m +/- 1)。
 *
 * 因此，公共的 2^k 不影响局面的胜负，
 * 我们只需要研究每个数的奇数部分。
 */
long long get(long long x)
{
    // x && 用来防止 x == 0 时一直执行 0 / 2。
    while(x && x % 2 == 0)
    {
        x /= 2;
    }

    return x;
}

/*
 * win(x) 表示：
 * 轮到当前玩家面对状态 x 时，当前玩家是否必胜。
 *
 * 博弈的基本原则：
 * - 只要存在一个后继状态是必败状态，当前状态就是必胜状态；
 * - 如果所有后继状态都是必胜状态，当前状态就是必败状态。
 */
bool win(long long x)
{
    // 只保留奇数部分，使后面的状态分析更加简单。
    x = get(x);

    // 题目规定 x == 0 时，轮到操作的人立即失败。
    if(x == 0)
    {
        return false;
    }

    /*
     * 奇数部分为 1，说明原来的数是 2 的幂：
     *
     * 原数 = 2^k * 1 = 2^k。
     *
     * 按照题意，这也是必败状态。
     */
    if(x == 1)
    {
        return false;
    }

    /*
     * x 已经是奇数。
     *
     * 对于任意奇数 x，两个操作对应研究 x - 1 和 x + 1。
     * x - 1、x、x + 1 是三个连续整数，其中必有一个是 3 的倍数。
     *
     * 除掉因子 2 不会除掉因子 3，因此：
     * 如果一个数原来是 3 的倍数，它的奇数部分仍是 3 的倍数。
     *
     * 可以证明，奇数的 3 的倍数一定是必胜状态。
     */
    if(x % 3 == 0)
    {
        return true;
    }

    /*
     * 如果 x % 3 == 1，那么 x - 1 是 3 的倍数。
     * 走向 x - 1 会把一个必胜状态交给对手，所以这个方向不能帮助我们获胜。
     *
     * 当前状态是否必胜，只取决于另一个方向：
     * next = get(x + 1)。
     *
     * 如果 next 是必败状态，我们就可以把 next 交给对手，当前状态必胜；
     * 如果 next 也是必胜状态，那么两个方向对对手都有利，当前状态必败。
     *
     * 因此，当前状态与 next 的胜负恰好相反，需要取反。
     */
    if(x % 3 == 1)
    {
        return !win(get(x + 1));
    }

    /*
     * 此处只剩 x % 3 == 2。
     *
     * 这时 x + 1 是 3 的倍数，是给对手的必胜状态，
     * 所以真正决定当前胜负的是另一个方向：
     * next = get(x - 1)。
     *
     * 同样，当前状态和 next 的胜负相反。
     *
     * 由于 x 是大于 1 的奇数，x - 1 一定是偶数；
     * get(x - 1) 至少会除以一次 2，所以新状态严格小于 x。
     * x % 3 == 1 的分支同理，因此递归不会形成循环。
     */
    return !win(get(x - 1));
}
 
int main()
{
    // 使用 long long，避免输入范围超过 int。
    long long x;
    cin >> x;

    // true 表示先手必胜，false 表示先手必败。
    if(win(x))
    {
        cout << "AAA" << endl;
    }
    else
    {
        cout << "BBB" << endl;
    }


    return 0;
}
